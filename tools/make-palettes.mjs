const BASE_HUE = 172;
// Tokens of the stylesheet defined from colour tokens (--green: var(--c-13796a) ...): a palette on a container (the previews) must resolve them again, so they are repeated in each block.
const derived = [...css.split('\n')[2].matchAll(/--([a-z-]+):var\(--c-([0-9a-f]{6})\)/g)].map(m => `    --${m[1]}:var(--c-${m[2]});`);

function toHsl(hex) {
    const r = parseInt(hex.slice(0, 2), 16) / 255, g = parseInt(hex.slice(2, 4), 16) / 255, b = parseInt(hex.slice(4, 6), 16) / 255;
    const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
    if (d === 0) return { h: 0, s: 0, l };
    const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    let h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    return { h: h * 60, s, l };
}
function toHex({ h, s, l }) {
    h = ((h % 360) + 360) % 360;
    const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs((h / 60) % 2 - 1)), m = l - c / 2;
    const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
    return [r, g, b].map(v => Math.round((v + m) * 255).toString(16).padStart(2, '0')).join('');
}

const original = { id: 'implicit', name: 'Verde original' };
let out = '/* Colour palettes of the LIGHT theme (Setari afisare -> Culori). GENERATED by tools/make-palettes.mjs - do not edit by hand. The attribute data-palette is on <html> (the choice of the user)\n   or on any container (the previews of Setari afisare). The dark theme ignores palettes. */\n';
const swatches = [];
{
    const lines = tokens.filter(({ hex }) => { const { s, h } = toHsl(hex); return !(s < 0.04 || h < 95 || h > 200); }).map(({ name, hex }) => `    --c-${name}:#${hex};`);
    out += `\n:root:not([data-theme="dark"])[data-palette="${original.id}"],\n:root:not([data-theme="dark"]) [data-palette="${original.id}"] {\n${lines.concat(derived).join('\n')}\n}\n`;
}
for (const p of palettes) {
    const lines = [];
    for (const { name, hex } of tokens) {
        const { h, s, l } = toHsl(hex);
        if (s < 0.04 || h < 95 || h > 200) continue;                       // greys, reds, ambers, blues stay
        const next = toHex({ h: p.hue + (h - BASE_HUE) * 0.6, s: s * p.sat, l: l + (1 - l) * (p.lift ?? 0) });
        if (next !== hex) lines.push(`    --c-${name}:#${next};`);
    }
    out += `\n:root:not([data-theme="dark"])[data-palette="${p.id}"],\n:root:not([data-theme="dark"]) [data-palette="${p.id}"] {\n${lines.concat(derived).join('\n')}\n}\n`;
    const accent = toHsl('13796a');
    swatches.push(`${p.id}: #${toHex({ h: p.hue, s: accent.s * p.sat, l: accent.l + (1 - accent.l) * (p.lift ?? 0) })}`);
}
writeFileSync(new URL('../wwwroot/theme-palettes.css', import.meta.url), out);
console.log(`tokens: ${tokens.length}; palettes: ${palettes.length}`);
console.log(swatches.join('\n'));
